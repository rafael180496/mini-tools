package agentctx

import (
	"fmt"
	"strings"

	"mini-tools/backend/i18n"
)

// InstructionPointer genera el contenido de un archivo de instrucciones que NO
// existe, como puntero corto al que sí existe (`source`).
//
// Es un puntero y no una copia, y esa es la decisión de fondo: dos archivos con
// el mismo texto se desincronizan en el primer cambio, y desde ahí cada CLI
// obedece una versión distinta de las reglas del proyecto. Por eso el archivo
// nuevo trae el contenido del original por referencia:
//
//   - CLAUDE.md importa con `@ruta`: Claude Code expande la línea con el
//     contenido real del archivo al cargar la memoria del proyecto.
//   - GEMINI.md importa con `@./ruta`: es la sintaxis de Gemini y Antigravity.
//   - AGENTS.md no puede: Codex y OpenCode no expanden imports, así que lleva
//     un puntero textual con un enlace markdown que el agente sigue leyendo el
//     archivo.
//
// Devuelve "" si `target` no es uno de los tres archivos, o si es el mismo que
// `source` (apuntar un archivo a sí mismo sería un import circular).
func InstructionPointer(target, source string) string {
	if target == source || source == "" {
		return ""
	}
	var b strings.Builder
	switch target {
	case "CLAUDE.md":
		b.WriteString(i18n.T(i18n.Msg{
			ES: "<!-- Generado por mini-tools: Claude Code lee CLAUDE.md y no %s, así que este archivo trae su contenido con un import. Para agregar reglas solo de Claude Code, escribilas debajo. -->\n\n",
			EN: "<!-- Generated by mini-tools: Claude Code reads CLAUDE.md and not %s, so this file pulls in its content with an import. To add rules for Claude Code only, write them below. -->\n\n",
		}, source))
		fmt.Fprintf(&b, "@%s\n", source)
	case "GEMINI.md":
		b.WriteString(i18n.T(i18n.Msg{
			ES: "<!-- Generado por mini-tools: Gemini y Antigravity leen GEMINI.md y no %s, así que este archivo trae su contenido con un import. Para agregar reglas solo de ellos, escribilas debajo. -->\n\n",
			EN: "<!-- Generated by mini-tools: Gemini and Antigravity read GEMINI.md and not %s, so this file pulls in its content with an import. To add rules for them only, write them below. -->\n\n",
		}, source))
		fmt.Fprintf(&b, "@./%s\n", source)
	case "AGENTS.md":
		b.WriteString(i18n.T(i18n.Msg{
			ES: "# Instrucciones del proyecto\n\n> Generado por mini-tools. Codex y OpenCode leen AGENTS.md y no %s, y no importan archivos; por eso este es un puntero y no una copia, que se desincronizaría.\n\n",
			EN: "# Project instructions\n\n> Generated by mini-tools. Codex and OpenCode read AGENTS.md and not %s, and they do not import files; that is why this is a pointer and not a copy, which would drift out of sync.\n\n",
		}, source))
		b.WriteString(i18n.T(i18n.Msg{
			ES: "Las instrucciones de este proyecto viven en [%s](%s): leelo antes de tocar nada y seguí lo que dice como si estuviera escrito acá.\n",
			EN: "This project's instructions live in [%s](%s): read it before touching anything and follow it as if it were written here.\n",
		}, source, source))
	default:
		return ""
	}
	return b.String()
}
